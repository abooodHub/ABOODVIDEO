"""Owner/admin quality ladder policy for future transcode jobs."""
from typing import Literal
import json

from fastapi import APIRouter, Depends, HTTPException, Response
from pydantic import BaseModel, Field
from sqlalchemy.ext.asyncio import AsyncSession

from app.core.config import settings
from app.core.database import get_db
from app.models.setting import SystemSetting
from app.security.auth import require_owner_or_admin
from app.security.csrf import check_csrf_protection
from app.services.quality_settings import SETTING_KEY, QUALITY_ORDER, normalize_qualities
from app.services.encoder_settings import ENCODER_SETTING_KEY, ENCODER_PRESETS, EncoderPolicy, read_transcode_controls, encoder_ladder_presets

router = APIRouter(
    prefix="/admin/quality-settings",
    tags=["Admin Quality Settings"],
    dependencies=[Depends(require_owner_or_admin), Depends(check_csrf_protection)],
)

Quality = Literal["360p", "480p", "720p", "1080p", "1440p", "2160p"]
PLAYBACK_SETTING_KEY = "playback_quality_policy"


class QualitySettingsPayload(BaseModel):
    enabled_qualities: list[Quality] = Field(min_length=1)


@router.get("")
async def read_quality_settings(response: Response, db: AsyncSession = Depends(get_db)):
    response.headers["Cache-Control"] = "no-store"
    row = await db.get(SystemSetting, SETTING_KEY)
    return {
        "enabled_qualities": normalize_qualities(row.value if row else None),
        "available_qualities": list(QUALITY_ORDER),
        "four_k_allowed": settings.ENABLE_4K_TRANSCODING,
    }


@router.put("")
async def update_quality_settings(
    payload: QualitySettingsPayload,
    response: Response,
    db: AsyncSession = Depends(get_db),
):
    response.headers["Cache-Control"] = "no-store"
    if len(payload.enabled_qualities) != len(set(payload.enabled_qualities)):
        raise HTTPException(status_code=422, detail="Duplicate rendition")
    if "2160p" in payload.enabled_qualities and not settings.ENABLE_4K_TRANSCODING:
        raise HTTPException(status_code=422, detail="4K transcoding is disabled by deployment policy")
    enabled = normalize_qualities(",".join(payload.enabled_qualities))
    row = await db.get(SystemSetting, SETTING_KEY)
    if row is None:
        db.add(SystemSetting(
            key=SETTING_KEY,
            value=",".join(enabled),
            description="Renditions generated by future transcode jobs; existing media is unchanged",
        ))
    else:
        row.value = ",".join(enabled)
    await db.commit()
    return {"enabled_qualities": enabled, "message": "Saved for future transcode jobs"}


class EncoderSettingsPayload(EncoderPolicy):
    enabled_qualities: list[Quality] = Field(min_length=1)


async def encoder_settings_response(db):
    enabled, policy = await read_transcode_controls(db)
    return {
        **policy.model_dump(),
        "enabled_qualities": enabled,
        "available_qualities": list(QUALITY_ORDER),
        "available_presets": list(ENCODER_PRESETS),
        "four_k_allowed": settings.ENABLE_4K_TRANSCODING,
        "video_codec": "H.264 (libx264 / CPU)", "audio_codec": "AAC",
        "quality_presets": encoder_ladder_presets(policy),
    }


@router.get("/encoder")
async def read_encoder_settings(response: Response, db: AsyncSession = Depends(get_db)):
    response.headers["Cache-Control"] = "no-store"
    return await encoder_settings_response(db)


@router.put("/encoder")
async def update_encoder_settings(payload: EncoderSettingsPayload, response: Response, db: AsyncSession = Depends(get_db)):
    response.headers["Cache-Control"] = "no-store"
    if len(payload.enabled_qualities) != len(set(payload.enabled_qualities)):
        raise HTTPException(status_code=422, detail="Duplicate rendition")
    if "2160p" in payload.enabled_qualities and not settings.ENABLE_4K_TRANSCODING:
        raise HTTPException(status_code=422, detail="4K transcoding is disabled by deployment policy")
    enabled = normalize_qualities(",".join(payload.enabled_qualities))
    policy = EncoderPolicy(preset=payload.preset, video_bitrate_percent=payload.video_bitrate_percent)
    values = {SETTING_KEY: ",".join(enabled), ENCODER_SETTING_KEY: policy.model_dump_json()}
    for key, value in values.items():
        row = await db.get(SystemSetting, key)
        if row is None:
            db.add(SystemSetting(key=key, value=value, description="Server encoder configuration for future transcode jobs"))
        else:
            row.value = value
    await db.commit()
    return await encoder_settings_response(db)


class PlaybackQualityPayload(BaseModel):
    enabled_qualities: list[Quality] = Field(min_length=1)


@router.get("/playback")
async def read_playback_quality(response: Response, db: AsyncSession = Depends(get_db)):
    """Quality visibility policy enforced on every HLS playlist and asset request."""
    response.headers["Cache-Control"] = "no-store"
    row = await db.get(SystemSetting, PLAYBACK_SETTING_KEY)
    try:
        configured = json.loads(row.value) if row else list(QUALITY_ORDER)
        enabled = [q for q in QUALITY_ORDER if q in configured]
        if not enabled:
            enabled = list(QUALITY_ORDER)
    except (TypeError, ValueError):
        enabled = list(QUALITY_ORDER)
    if not settings.ENABLE_4K_TRANSCODING:
        enabled = [q for q in enabled if q != "2160p"]
    available = [q for q in QUALITY_ORDER if settings.ENABLE_4K_TRANSCODING or q != "2160p"]
    return {"enabled_qualities": enabled, "available_qualities": available}


@router.put("/playback")
async def update_playback_quality(payload: PlaybackQualityPayload, response: Response, db: AsyncSession = Depends(get_db)):
    response.headers["Cache-Control"] = "no-store"
    if len(payload.enabled_qualities) != len(set(payload.enabled_qualities)):
        raise HTTPException(status_code=422, detail="Duplicate rendition")
    if "2160p" in payload.enabled_qualities and not settings.ENABLE_4K_TRANSCODING:
        raise HTTPException(status_code=422, detail="4K is disabled by deployment policy")
    value = json.dumps([q for q in QUALITY_ORDER if q in payload.enabled_qualities])
    row = await db.get(SystemSetting, PLAYBACK_SETTING_KEY)
    if row is None:
        db.add(SystemSetting(key=PLAYBACK_SETTING_KEY, value=value,
                             description="Renditions visible to viewers; enforced on HLS requests"))
    else:
        row.value = value
    await db.commit()
    return {"enabled_qualities": json.loads(value)}
